import { test, expect } from '@playwright/test'

test('canvas prompts and model settings survive reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('button', { name: '工作空间', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '创作工作台' })).toHaveCount(0)
  await page.getByRole('button', { name: '新建项目', exact: true }).first().click()
  await expect(page.locator('.cc-canvas')).toBeVisible()
  await page.keyboard.press('i')
  await page.getByLabel('描述这张图片', { exact: true }).fill('A red fox beside a calm lake.')
  await page.getByRole('button', { name: '节点设置', exact: true }).click()
  await page.getByRole('button', { name: 'MOSS Image', exact: true }).click()
  await page.getByRole('button', { name: '3:2', exact: true }).click()
  await page.getByRole('button', { name: '关闭设置', exact: true }).click()
  await expect(page.locator('.cc-sidebar-save')).toHaveText('已保存')
  await page.reload()
  await expect(page.getByTestId('card-image')).toHaveCount(1)
  await page.getByTestId('card-image').click()
  await expect(page.getByLabel('描述这张图片', { exact: true })).toHaveValue('A red fox beside a calm lake.')
  await expect(page.locator('.cc-model-label')).toHaveText('MOSS Image')
  expect(errors).toEqual([])
})

test('group, undo, ungroup, duplicate and delete preserve canvas members', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '新建项目', exact: true }).first().click()
  await expect(page.locator('.cc-canvas')).toBeVisible()
  await page.keyboard.press('i')
  await page.keyboard.press('v')
  await page.getByRole('button', { name: '选择 (Shift 多选)', exact: true }).click()
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.press('ControlOrMeta+g')
  await expect(page.locator('.cc-group-card')).toHaveCount(1)
  await page.keyboard.press('ControlOrMeta+z')
  await expect(page.locator('.cc-group-card')).toHaveCount(0)
  await page.keyboard.press('ControlOrMeta+Shift+z')
  await expect(page.locator('.cc-group-card')).toHaveCount(1)
  await page.keyboard.press('ControlOrMeta+Shift+g')
  await expect(page.locator('.react-flow__node')).toHaveCount(2)
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.press('ControlOrMeta+d')
  await expect(page.locator('.react-flow__node')).toHaveCount(4)
  await page.keyboard.press('Delete')
  await expect(page.locator('.react-flow__node')).toHaveCount(2)
})

test('advanced panel opens resources and commands without allocating', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '打开服务器高级面板', exact: true }).click()
  const panel = page.getByRole('dialog', { name: '服务器高级面板' })
  await expect(panel.getByRole('button', { name: '连接服务器', exact: true })).toBeVisible()
  await expect(panel.getByText('GPU 功率', { exact: true })).toBeVisible()
  await panel.getByRole('button', { name: '命令行', exact: true }).click()
  await expect(panel.getByLabel('服务器命令', { exact: true })).toHaveValue('nvidia-smi')
  await expect(page.getByRole('button', { name: '释放', exact: true })).toBeDisabled()
})
